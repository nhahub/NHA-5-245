create table if not exists public.sg_services (
  id text primary key,
  name text not null,
  provider_name text not null,
  target_url text not null check (target_url ~ '^https?://[^[:space:]]+$'),
  expected_status integer not null default 200 check (expected_status between 100 and 599),
  timeout_ms integer not null default 10000 check (timeout_ms between 1000 and 20000),
  max_sample_gap_seconds integer not null default 90 check (max_sample_gap_seconds between 1 and 3600),
  sla_target_pct numeric(7,4) not null default 99.9000 check (sla_target_pct > 0 and sla_target_pct <= 100),
  credit_pct numeric(7,4) not null default 10 check (credit_pct between 0 and 100),
  monthly_fee numeric(12,2) not null default 100 check (monthly_fee >= 0),
  currency text not null default 'USD' check (currency ~ '^[A-Z]{3}$'),
  contract_reference text not null default 'FICTIONAL-DEMO-SLA-v1',
  enabled boolean not null default true
);

create table if not exists public.sg_checks (
  id bigint generated by default as identity primary key,
  service_id text not null references public.sg_services(id),
  source text not null default 'live' check (source in ('live', 'demo')),
  execution_id text not null check (length(execution_id) between 1 and 200),
  checked_at timestamptz not null,
  recorded_at timestamptz not null default clock_timestamp(),
  is_up boolean not null,
  status_code integer check (status_code between 100 and 599),
  response_ms integer check (response_ms >= 0),
  error text check (length(error) <= 500),
  unique (service_id, source, execution_id)
);
create index if not exists sg_checks_timeline_idx
  on public.sg_checks(service_id, source, checked_at desc, id desc);

create table if not exists public.sg_reports (
  id uuid primary key default gen_random_uuid(),
  service_id text not null references public.sg_services(id),
  month date not null check (extract(day from month) = 1),
  source text not null check (source in ('live', 'demo')),
  revision integer not null default 1,
  generation_execution_id text not null,
  generated_at timestamptz not null default clock_timestamp(),
  report jsonb not null,
  claim_draft text not null,
  unique (service_id, month, source)
);

