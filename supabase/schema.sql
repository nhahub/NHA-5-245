-- A single insert is atomic. HTTP-node retries reuse the same execution ID.
create or replace function public.sg_record_check(
  p_service_id text, p_execution_id text, p_checked_at timestamptz,
  p_is_up boolean, p_status_code integer, p_response_ms integer, p_error text
) returns jsonb
language plpgsql security invoker set search_path = '' set timezone = 'UTC'
as $$
declare
  s public.sg_services%rowtype;
  c public.sg_checks%rowtype;
  prev public.sg_checks%rowtype;
  duplicate boolean := false;
  transition text;
begin
  select * into strict s from public.sg_services where id = p_service_id;
  if not s.enabled then raise exception 'Service is disabled'; end if;
  if p_checked_at is null or p_checked_at > clock_timestamp() + interval '90 seconds' then
    raise exception 'Invalid check time; synchronize the n8n host clock';
  end if;
  if p_is_up is distinct from coalesce(p_status_code = s.expected_status and p_error is null, false) then
    raise exception 'is_up does not match expected HTTP status / error';
  end if;

  insert into public.sg_checks(service_id, source, execution_id, checked_at, is_up, status_code, response_ms, error)
  values (p_service_id, 'live', p_execution_id, p_checked_at, p_is_up, p_status_code, p_response_ms, p_error)
  on conflict (service_id, source, execution_id) do nothing
  returning * into c;
  if c.id is null then
    duplicate := true;
    select * into strict c from public.sg_checks
    where service_id = p_service_id and source = 'live' and execution_id = p_execution_id;
  end if;
  select * into prev from public.sg_checks
  where service_id = c.service_id and source = 'live'
    and (checked_at, id) < (c.checked_at, c.id)
  order by checked_at desc, id desc limit 1;
  transition := case
    when exists (select 1 from public.sg_checks where service_id = c.service_id and source = 'live'
      and (checked_at, id) > (c.checked_at, c.id)) then 'recorded_out_of_order'
    when prev.id is null then case when c.is_up then 'initial_up' else 'initial_down' end
    when extract(epoch from c.checked_at - prev.checked_at) > s.max_sample_gap_seconds
      then case when c.is_up then 'resumed_up_after_gap' else 'resumed_down_after_gap' end
    when prev.is_up = c.is_up then 'unchanged'
    when c.is_up then 'recovered' else 'outage_started' end;
  return jsonb_build_object('check', to_jsonb(c), 'transition', transition, 'duplicate', duplicate);
end;
$$;

create or replace function public.sg_status(p_service_id text, p_source text default 'live')
returns jsonb
language plpgsql security invoker set search_path = '' set timezone = 'UTC'
as $$
declare
  s public.sg_services%rowtype;
  c public.sg_checks%rowtype;
  recent jsonb;
begin
  if p_source not in ('live','demo') or p_source is null then raise exception 'Invalid dataset'; end if;
  select * into strict s from public.sg_services where id = p_service_id;
  select * into c from public.sg_checks where service_id = p_service_id and source = p_source
    order by checked_at desc, id desc limit 1;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.checked_at desc, x.id desc), '[]'::jsonb) into recent
    from (select * from public.sg_checks where service_id = p_service_id and source = p_source
      order by checked_at desc, id desc limit 20) x;
  return jsonb_build_object(
    'service', to_jsonb(s), 'dataset', p_source, 'is_synthetic', p_source = 'demo',
    'current_status', case when c.id is null then 'unknown'
      when c.checked_at + make_interval(secs => s.max_sample_gap_seconds) < clock_timestamp() then 'unknown'
      when c.is_up then 'up' else 'down' end,
    'latest_check', case when c.id is null then null else to_jsonb(c) end, 'recent_checks', recent);
end;
$$;

-- The report is derived from timestamped evidence, not mutable workflow state.
-- A sample carries forward to the next sample, capped at max_sample_gap_seconds.
-- Uncovered time is UNKNOWN, never automatically classified as uptime.
create or replace function public.sg_monthly_report(
  p_service_id text, p_month date, p_source text, p_execution_id text
) returns jsonb
language plpgsql security invoker set search_path = '' set timezone = 'UTC'
as $$
declare
  s public.sg_services%rowtype;
  saved public.sg_reports%rowtype;
  v_start timestamptz;
  v_end timestamptz;
  v_as_of timestamptz := clock_timestamp();
  v_until timestamptz;
  v_elapsed numeric;
  v_up numeric := 0;
  v_down numeric := 0;
  v_unknown numeric;
  v_count bigint;
  v_windows jsonb;
  v_best numeric;
  v_worst numeric;
  v_observed numeric;
  v_final boolean;
  v_assessment text;
  v_credit_pct numeric := 0;
  v_credit_amount numeric := 0;
  v_report jsonb;
  v_draft text;
begin
  if p_source not in ('live','demo') or p_source is null then raise exception 'Invalid dataset'; end if;
  if p_month is null or extract(day from p_month) <> 1 then raise exception 'Month must be its first date'; end if;
  if p_execution_id is null or length(p_execution_id) not between 1 and 200 then raise exception 'Invalid execution ID'; end if;
  select * into strict s from public.sg_services where id = p_service_id;
  v_start := p_month::timestamp at time zone 'UTC';
  v_end := (p_month + interval '1 month')::timestamp at time zone 'UTC';
  if v_start > v_as_of then raise exception 'Future months cannot be assessed'; end if;
  v_until := least(v_end, v_as_of);
  v_elapsed := extract(epoch from v_until - v_start);
  v_final := v_as_of >= v_end;

  perform pg_advisory_xact_lock(hashtextextended(p_service_id || '|' || p_month || '|' || p_source, 0));
  select * into saved from public.sg_reports
    where service_id = p_service_id and month = p_month and source = p_source;
  if saved.id is not null and saved.generation_execution_id = p_execution_id then
    return jsonb_build_object('report_id', saved.id, 'revision', saved.revision,
      'report', saved.report, 'claim_draft', saved.claim_draft, 'duplicate', true);
  end if;

  with ordered as (
    select id, checked_at, is_up,
      lead(checked_at, 1, v_until) over (order by checked_at, id) as next_at
    from public.sg_checks
    where service_id = p_service_id and source = p_source
      and checked_at >= v_start - make_interval(secs => s.max_sample_gap_seconds)
      and checked_at < v_until
  ), spans as (
    select is_up, greatest(checked_at, v_start) as a,
      least(next_at, checked_at + make_interval(secs => s.max_sample_gap_seconds), v_until) as b
    from ordered
  ), valid as (
    select *, extract(epoch from b-a) as seconds from spans where b > a
  ), down_marks as (
    select *, case when lag(b) over (order by a, b) = a then 0 else 1 end as new_window
    from valid where not is_up
  ), grouped as (
    select *, sum(new_window) over (order by a, b rows unbounded preceding) as window_id from down_marks
  ), windows as (
    select min(a) as started_at, max(b) as ended_at, sum(seconds) as duration_seconds
    from grouped group by window_id
  )
  select
    coalesce((select sum(seconds) from valid where is_up), 0),
    coalesce((select sum(seconds) from valid where not is_up), 0),
    coalesce((select jsonb_agg(to_jsonb(w) order by started_at) from windows w), '[]'::jsonb)
  into v_up, v_down, v_windows;

  select count(*) into v_count from public.sg_checks where service_id = p_service_id and source = p_source
    and checked_at >= v_start and checked_at < v_until;
  v_unknown := greatest(0, v_elapsed - v_up - v_down);
  v_best := 100 * (v_elapsed - v_down) / nullif(v_elapsed, 0);
  v_worst := 100 * v_up / nullif(v_elapsed, 0);
  v_observed := 100 * v_up / nullif(v_up + v_down, 0);
  v_assessment := case
    when v_up + v_down = 0 then 'insufficient_data'
    when not v_final then 'provisional'
    when v_unknown > 0 then 'needs_data_review'
    when v_best < s.sla_target_pct then 'breach_detected'
    else 'within_sla' end;
  if v_assessment = 'breach_detected' then
    v_credit_pct := s.credit_pct;
    v_credit_amount := round(s.monthly_fee * v_credit_pct / 100, 2);
  end if;

  v_report := jsonb_build_object(
    'service_id', s.id, 'service_name', s.name, 'provider_name', s.provider_name,
    'month', to_char(p_month, 'YYYY-MM'), 'dataset', p_source, 'is_synthetic', p_source = 'demo',
    'period_start', v_start, 'period_end', v_end, 'assessed_until', v_until, 'generated_at', v_as_of,
    'is_final', v_final, 'execution_id', p_execution_id, 'contract_snapshot', to_jsonb(s),
    'measurement_method', 'Sample status held until next sample, capped at max_sample_gap_seconds; all uncovered time unknown. These are polling estimates.',
    'period_seconds', extract(epoch from v_end - v_start), 'elapsed_seconds', v_elapsed,
    'up_seconds', v_up, 'down_seconds', v_down, 'unknown_seconds', v_unknown,
    'coverage_pct', round(100 * (v_up + v_down) / nullif(v_elapsed, 0), 6),
    'observed_availability_pct', round(v_observed, 6),
    'availability_upper_estimate_pct', round(v_best, 6),
    'availability_lower_estimate_pct', round(v_worst, 6),
    'estimated_monthly_availability_pct', case when v_final and v_unknown = 0 then round(v_best, 6) else null end,
    'sample_count', v_count, 'down_windows', v_windows,
    'assessment', v_assessment, 'candidate_credit_pct', v_credit_pct,
    'candidate_credit_amount', v_credit_amount, 'currency', s.currency,
    'review_required', true, 'claim_status', case when p_source = 'demo' then 'demonstration_only' else 'draft_for_review' end);

  v_draft := format(E'DRAFT - HUMAN REVIEW REQUIRED%s\nService: %s\nProvider: %s\nContract: %s\nBilling month: %s (UTC)\nAssessment: %s\nEstimated observed downtime: %s minutes\nUnknown monitoring time: %s minutes\nEstimated monthly availability: %s\nSLA target: %s%%\nMonthly fee: %s %s\nCandidate service credit: %s%% = %s %s\nEvidence samples: %s; dataset: %s; n8n execution: %s\n\nPlease review the attached report and timestamped checks. These are polling estimates from one monitoring location. Provider responsibility, contractual exclusions, maintenance, and any claim deadline require human verification. This draft has not been submitted.\n%s',
    case when p_source = 'demo' then ' - SYNTHETIC DEMONSTRATION' else '' end,
    s.name, s.provider_name, s.contract_reference, to_char(p_month,'YYYY-MM'), v_assessment,
    round(v_down/60, 3), round(v_unknown/60, 3),
    case when v_final and v_unknown = 0 then round(v_best,6)::text || '%' else 'Not determined: incomplete period or monitoring gaps' end,
    s.sla_target_pct, s.monthly_fee, s.currency, v_credit_pct, v_credit_amount, s.currency,
    v_count, p_source, p_execution_id,
    case when p_source = 'demo' then 'SYNTHETIC DATA. The credit is an example and must never be submitted as a real claim.' else '' end);

  insert into public.sg_reports(service_id, month, source, generation_execution_id, generated_at, report, claim_draft)
  values (p_service_id, p_month, p_source, p_execution_id, v_as_of, v_report, v_draft)
  on conflict (service_id, month, source) do update set
    revision = public.sg_reports.revision + 1,
    generation_execution_id = excluded.generation_execution_id,
    generated_at = excluded.generated_at, report = excluded.report, claim_draft = excluded.claim_draft
  returning * into saved;
  return jsonb_build_object('report_id', saved.id, 'revision', saved.revision,
    'report', saved.report, 'claim_draft', saved.claim_draft, 'duplicate', false);
end;
$$;

